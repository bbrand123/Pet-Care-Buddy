const fs = require('fs');
const path = require('path');
const config = require('./runtime-manifest.config.cjs');

function walk(dirAbs, dirRel, out) {
  if (!fs.existsSync(dirAbs)) return;
  const entries = fs.readdirSync(dirAbs, { withFileTypes: true });
  for (const entry of entries) {
    const abs = path.join(dirAbs, entry.name);
    const rel = path.posix.join(dirRel, entry.name);
    if (entry.isDirectory()) {
      walk(abs, rel, out);
      continue;
    }
    out.push(rel);
  }
}

function uniqSorted(list) {
  return Array.from(new Set(list)).sort();
}

function toSwPath(relPath) {
  const clean = relPath.replace(/^\.\//, '');
  return clean === '' ? './' : `./${clean}`;
}

function writeFile(relPath, contents) {
  const filePath = path.join(config.repoRoot, relPath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
}

function buildRuntimeManifestJs(groups) {
  const lines = [];
  lines.push('// Generated by scripts/generate-runtime-manifests.cjs');
  for (const [name, arr] of Object.entries(groups)) {
    lines.push(`export const ${name} = Object.freeze(${JSON.stringify(arr, null, 2)});`);
    lines.push('');
  }
  lines.push('export const RUNTIME_SCRIPT_FILES = Object.freeze([');
  lines.push('  ...BASE_RUNTIME_FILES,');
  lines.push('  ...GAME_RUNTIME_FILES,');
  lines.push('  ...UI_RUNTIME_FILES,');
  lines.push('  ...MINIGAME_RUNTIME_FILES,');
  lines.push('  ...COMPETITION_RUNTIME_FILES');
  lines.push(']);');
  lines.push('');
  return lines.join('\n');
}

function buildSwAssetsJs(assets) {
  return `// Generated by scripts/generate-runtime-manifests.cjs\nself.SW_GENERATED_ASSETS = Object.freeze(${JSON.stringify(assets, null, 2)});\n`;
}

(function main() {
  const groups = {
    BASE_RUNTIME_FILES: config.BASE_RUNTIME_FILES,
    GAME_RUNTIME_FILES: config.GAME_RUNTIME_FILES,
    UI_RUNTIME_FILES: config.UI_RUNTIME_FILES,
    MINIGAME_RUNTIME_FILES: config.MINIGAME_RUNTIME_FILES,
    COMPETITION_RUNTIME_FILES: config.COMPETITION_RUNTIME_FILES
  };

  writeFile('js/config/runtime-manifest.generated.js', buildRuntimeManifestJs(groups));

  const scanned = [];
  for (const dirRel of config.SCAN_DIRS) {
    walk(path.join(config.repoRoot, dirRel), dirRel, scanned);
  }

  const runtimeJs = config.RUNTIME_BOOT_FILES.concat(
    groups.BASE_RUNTIME_FILES.map((p) => `./js/${p.replace(/^\.\//, '')}`),
    groups.GAME_RUNTIME_FILES.map((p) => `./js/${p.replace(/^\.\//, '')}`),
    groups.UI_RUNTIME_FILES.map((p) => `./js/${p.replace(/^\.\//, '')}`),
    groups.MINIGAME_RUNTIME_FILES.map((p) => `./js/${p.replace(/^\.\//, '')}`),
    groups.COMPETITION_RUNTIME_FILES.map((p) => `./js/${p.replace(/^\.\//, '')}`)
  );

  const scannedPrefixed = scanned
    .filter((rel) => !config.EXCLUDE_ASSET_PATHS.has(rel))
    .map(toSwPath);

  const allAssets = uniqSorted(
    config.ROOT_STATIC_FILES
      .concat(config.EXTRA_STATIC_FILES)
      .concat(runtimeJs)
      .concat(scannedPrefixed)
      .map(toSwPath)
  );

  writeFile('sw-assets.generated.js', buildSwAssetsJs(allAssets));

  console.log('Generated runtime manifest and SW assets:', {
    runtimeGroups: Object.fromEntries(Object.entries(groups).map(([k, v]) => [k, v.length])),
    swAssets: allAssets.length
  });
})();
